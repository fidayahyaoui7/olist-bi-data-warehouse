-- Star schema for the Olist data warehouse
-- Schema "dw" = the warehouse. Tables are created empty, data comes in Step 3 (ETL).

CREATE SCHEMA IF NOT EXISTS dw;

-- ============ DIMENSIONS ============

CREATE TABLE dw.dim_date (
    date_key      INT PRIMARY KEY,          -- format YYYYMMDD, -1 = not available
    full_date     DATE,
    year          INT,
    quarter       INT,
    month         INT,
    month_name    VARCHAR(20),
    year_month    VARCHAR(7),
    week_of_year  INT,
    day_of_week   INT,
    day_name      VARCHAR(20),
    is_weekend    BOOLEAN
);

CREATE TABLE dw.dim_customer (
    customer_key        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id  VARCHAR(50) NOT NULL UNIQUE,
    zip_code_prefix     INT,
    city                VARCHAR(100),
    state               CHAR(2),
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION
);

CREATE TABLE dw.dim_product (
    product_key         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          VARCHAR(50) NOT NULL UNIQUE,
    category_name_pt    VARCHAR(100),
    category_name_en    VARCHAR(100),
    name_length         INT,
    description_length  INT,
    photos_qty          INT,
    weight_g            INT,
    length_cm           INT,
    height_cm           INT,
    width_cm            INT
);

CREATE TABLE dw.dim_seller (
    seller_key       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        VARCHAR(50) NOT NULL UNIQUE,
    zip_code_prefix  INT,
    city             VARCHAR(100),
    state            CHAR(2),
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION
);

CREATE TABLE dw.dim_order_status (
    order_status_key   INT PRIMARY KEY,
    order_status       VARCHAR(20) NOT NULL UNIQUE,
    is_revenue_status  BOOLEAN NOT NULL,    -- false for canceled and unavailable
    is_delivered       BOOLEAN NOT NULL
);

-- ============ FACT TABLES ============

-- Grain: one item of an order
CREATE TABLE dw.fact_sales (
    order_id           VARCHAR(50) NOT NULL,
    order_item_id      INT NOT NULL,
    purchase_date_key  INT NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key       INT NOT NULL REFERENCES dw.dim_customer(customer_key),
    product_key        INT NOT NULL REFERENCES dw.dim_product(product_key),
    seller_key         INT NOT NULL REFERENCES dw.dim_seller(seller_key),
    order_status_key   INT NOT NULL REFERENCES dw.dim_order_status(order_status_key),
    price              NUMERIC(12,2) NOT NULL,
    freight_value      NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (order_id, order_item_id)
);

-- Grain: one order
CREATE TABLE dw.fact_orders (
    order_id             VARCHAR(50) PRIMARY KEY,
    customer_key         INT NOT NULL REFERENCES dw.dim_customer(customer_key),
    order_status_key     INT NOT NULL REFERENCES dw.dim_order_status(order_status_key),
    purchase_date_key    INT NOT NULL REFERENCES dw.dim_date(date_key),
    approved_date_key    INT NOT NULL REFERENCES dw.dim_date(date_key),
    carrier_date_key     INT NOT NULL REFERENCES dw.dim_date(date_key),
    delivered_date_key   INT NOT NULL REFERENCES dw.dim_date(date_key),
    estimated_date_key   INT NOT NULL REFERENCES dw.dim_date(date_key),
    delivery_days        INT,
    delay_days           INT,                -- negative = delivered early
    is_on_time           BOOLEAN,
    items_count          INT NOT NULL DEFAULT 0,
    items_total          NUMERIC(12,2),
    payment_total        NUMERIC(12,2),
    payment_count        INT NOT NULL DEFAULT 0,
    max_installments     INT,
    main_payment_type    VARCHAR(30),
    review_score         SMALLINT
);

